// Writes mobile/src/audio/generated/reciterCatalog.ts from reciters.mjs and audit-results.json, and
// mobile/src/audio/generated/measuredTiming.ts from measured-timing.json (both written by refine-results.mjs).
// usage: node generate-catalog.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { RECITERS } from './reciters.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const results = JSON.parse(fs.readFileSync(path.join(here, 'audit-results.json'), 'utf8'));
const byId = new Map(results.reciters.map((r) => [r.id, r]));
const measuredFile = path.join(here, 'measured-timing.json');
const measured = fs.existsSync(measuredFile) ? JSON.parse(fs.readFileSync(measuredFile, 'utf8')) : { reciters: {} };

const lines = [];
lines.push('// GENERATED by tools/quran-audio/generate-catalog.mjs from tools/quran-audio/audit-results.json. Do not edit.');
lines.push('/**');
lines.push(` * The ${RECITERS.length} Quran Heals reciters and the MP3Quran recording used for each (audited ${results.auditedOn}, refined ${results.refinedOn}).`);
lines.push(' * `surahs`: the surahs the recording has. `timed`: the surahs whose ayah timing passed every check (complete Kufan');
lines.push(' * ayah set, ordered, inside the audio, and checked against the audio itself), with the fingerprint of the exact');
lines.push(' * timing that was checked (audio/timingFingerprint.ts) and the audio file\'s size in bytes. A surah missing from');
lines.push(' * `timed` has no ayah playback for that reciter. See tools/quran-audio/README.md.');
lines.push(' */');
lines.push('export type GeneratedReciter = {');
lines.push('  id: string;');
lines.push('  nameEn: string;');
lines.push('  nameAr: string;');
lines.push('  /** MP3Quran reciter and recording ids; null for a reciter with no recording in the app. */');
lines.push('  mp3quranReciterId: number | null;');
lines.push('  moshafId: number | null;');
lines.push('  /** The recording\'s folder; a surah is `${server}${surah padded to 3}.mp3`. Null: no recording in the app. */');
lines.push('  server: string | null;');
lines.push("  style: 'murattal' | 'mujawwad';");
lines.push("  /** 'hafs': MP3Quran labels the recording حفص عن عاصم; 'unlabelled': it names no riwaya (Kufan ayah count verified). */");
lines.push("  /** null: no recording in the app. */");
lines.push("  riwayaLabel: 'hafs' | 'unlabelled' | null;");
lines.push('  surahs: readonly number[];');
lines.push('  /**');
lines.push("   * Where the timing comes from: 'mp3quran', MP3Quran's own (read `timingRead`, fetched at run time); 'measured', measured");
lines.push('   * by the audit for this same MP3Quran file and shipped in the app (generated/measuredTiming.ts); null: none.');
lines.push('   */');
lines.push("  timingSource: 'mp3quran' | 'measured' | null;");
lines.push('  /** MP3Quran timing read id, or null when MP3Quran timing is not used. */');
lines.push('  timingRead: number | null;');
lines.push('  timed: Readonly<Record<number, readonly [fingerprint: string, bytes: number]>>;');
lines.push('};');
lines.push('');
lines.push('export const GENERATED_RECITERS: readonly GeneratedReciter[] = [');
for (const r of RECITERS) {
  const a = byId.get(r.id);
  if (!a) throw new Error(`no audit result for ${r.id}`);
  if (!('timingSource' in a)) throw new Error('audit-results.json has not been refined: run refine-results.mjs');
  const timed = Object.entries(a.timed).map(([s, t]) => `${s}: ['${t.fingerprint}', ${a.bytes[s]}]`);
  lines.push('  {');
  lines.push(`    id: '${r.id}', nameEn: '${r.nameEn}', nameAr: '${r.nameAr}', mp3quranReciterId: ${r.reciterId}, moshafId: ${r.moshafId},`);
  const q = (v) => (v === null ? 'null' : `'${v}'`);
  lines.push(`    server: ${q(a.server)}, style: '${r.style}', riwayaLabel: ${q(r.riwayaLabel)},`);
  lines.push(`    timingSource: ${a.timingSource ? `'${a.timingSource}'` : 'null'}, timingRead: ${a.timingRead ?? 'null'},`);
  lines.push(`    surahs: [${a.surahs.join(', ')}],`);
  if (timed.length === 0) lines.push('    timed: {},');
  else {
    lines.push('    timed: {');
    for (let i = 0; i < timed.length; i += 4) lines.push(`      ${timed.slice(i, i + 4).join(', ')},`);
    lines.push('    },');
  }
  lines.push('  },');
}
lines.push('];');
lines.push('');
const generated = path.join(here, '..', '..', 'mobile', 'src', 'audio', 'generated');
fs.mkdirSync(generated, { recursive: true });
const target = path.join(generated, 'reciterCatalog.ts');
fs.writeFileSync(target, lines.join('\n'));
console.log('wrote', target, fs.statSync(target).size, 'bytes');

// Measured timing: per surah, the ayah boundaries in ms, delta-encoded (start of ayah 1, then each ayah's length).
// Every ayah ends where the next starts (the boundary sits in the measured pause), so N+1 numbers give N ayahs.
const m = [];
m.push('// GENERATED by tools/quran-audio/generate-catalog.mjs from tools/quran-audio/measured-timing.json. Do not edit.');
m.push("import type { TimingEntry } from '../timingFingerprint';");
m.push('');
m.push('/**');
m.push(' * Ayah timing measured by the audit (tools/quran-audio/refine-results.mjs) for reciters whose MP3Quran recording has no');
m.push(' * usable MP3Quran timing: per surah, in that same MP3Quran file, the start of ayah 1 and then each ayah\'s length (ms).');
m.push(" * Used only through audio/timing.ts, which checks it against the catalogue's fingerprint like any other timing.");
m.push(' */');
m.push('const MEASURED: Readonly<Record<string, Readonly<Record<number, readonly number[]>>>> = {');
for (const r of RECITERS) {
  const mr = measured.reciters[r.id];
  if (!mr) continue;
  if (byId.get(r.id).timingSource !== 'measured') throw new Error(`${r.id}: measured timing without timingSource 'measured'`);
  m.push(`  '${r.id}': {`);
  for (const [s, ayahs] of Object.entries(mr.surahs)) {
    ayahs.forEach(([, end], k) => {
      if (k + 1 < ayahs.length && end !== ayahs[k + 1][0]) throw new Error(`${r.id} ${s}:${k + 1} does not end where the next starts`);
    });
    const points = [...ayahs.map(([start]) => start), ayahs.at(-1)[1]];
    m.push(`    ${s}: [${points.map((p, k) => (k === 0 ? p : p - points[k - 1])).join(', ')}],`);
  }
  m.push('  },');
}
m.push('};');
m.push('');
m.push('/** The measured timing of one surah as timing entries (ayahs 1..N), or null when there is none. */');
m.push('export function measuredTimingEntries(reciterId: string, surah: number): TimingEntry[] | null {');
m.push('  const deltas = MEASURED[reciterId]?.[surah];');
m.push('  if (!deltas || deltas.length < 2) return null;');
m.push('  const entries: TimingEntry[] = [];');
m.push('  let at = deltas[0];');
m.push('  for (let k = 1; k < deltas.length; k++) {');
m.push('    entries.push({ ayah: k, startMs: at, endMs: at + deltas[k] });');
m.push('    at += deltas[k];');
m.push('  }');
m.push('  return entries;');
m.push('}');
m.push('');
const measuredTarget = path.join(generated, 'measuredTiming.ts');
fs.writeFileSync(measuredTarget, m.join('\n'));
console.log('wrote', measuredTarget, fs.statSync(measuredTarget).size, 'bytes');
