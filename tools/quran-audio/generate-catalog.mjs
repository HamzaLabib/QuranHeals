// Writes mobile/src/audio/generated/reciterCatalog.ts from reciters.mjs and audit-results.json,
// mobile/src/audio/generated/measuredTiming.ts from measured-timing.json (both written by refine-results.mjs), and
// mobile/src/audio/generated/sourceRegistry.ts from providers.mjs, audit-data/recording-formats-*.json and
// surah-mode-approvals.json.
// usage: node generate-catalog.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { timingFingerprint } from './fingerprint.mjs';
import { PROVIDERS } from './providers.mjs';
import { RECITERS } from './reciters.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const results = JSON.parse(fs.readFileSync(path.join(here, 'audit-results.json'), 'utf8'));
const byId = new Map(results.reciters.map((r) => [r.id, r]));
const measuredFile = path.join(here, 'measured-timing.json');
const measured = fs.existsSync(measuredFile) ? JSON.parse(fs.readFileSync(measuredFile, 'utf8')) : { reciters: {} };

const lines = [];
lines.push('// GENERATED by tools/quran-audio/generate-catalog.mjs from tools/quran-audio/audit-results.json. Do not edit.');
lines.push('/**');
lines.push(` * The ${RECITERS.length} Quran Heals reciters and the MP3Quran recording used for each (audited ${results.auditedOn}, refined ${results.refinedOn}).`);
lines.push(' * `surahs`: the surahs the recording has. `timed`: the surahs whose ayah timing passed every check (complete Kufan');
lines.push(' * ayah set, ordered, inside the audio, and checked against the audio itself), with the fingerprint of the exact');
lines.push(' * timing that was checked (audio/timingFingerprint.ts) and the audio file\'s size in bytes. A surah missing from');
lines.push(' * `timed` has no ayah playback for that reciter. See tools/quran-audio/README.md.');
lines.push(' */');
lines.push('export type GeneratedReciter = {');
lines.push('  id: string;');
lines.push('  nameEn: string;');
lines.push('  nameAr: string;');
lines.push('  /** MP3Quran reciter and recording ids; null for a reciter with no recording in the app. */');
lines.push('  mp3quranReciterId: number | null;');
lines.push('  moshafId: number | null;');
lines.push('  /** The recording\'s folder; a surah is `${server}${surah padded to 3}.mp3`. Null: no recording in the app. */');
lines.push('  server: string | null;');
lines.push("  style: 'murattal' | 'mujawwad';");
lines.push("  /** 'hafs': MP3Quran labels the recording حفص عن عاصم; 'unlabelled': it names no riwaya (Kufan ayah count verified). */");
lines.push("  /** null: no recording in the app. */");
lines.push("  riwayaLabel: 'hafs' | 'unlabelled' | null;");
lines.push('  surahs: readonly number[];');
lines.push('  /**');
lines.push("   * Where the timing comes from: 'mp3quran', MP3Quran's own (read `timingRead`, fetched at run time); 'measured', measured");
lines.push('   * by the audit for this same MP3Quran file and shipped in the app (generated/measuredTiming.ts); null: none.');
lines.push('   */');
lines.push("  timingSource: 'mp3quran' | 'measured' | null;");
lines.push('  /** MP3Quran timing read id, or null when MP3Quran timing is not used. */');
lines.push('  timingRead: number | null;');
lines.push('  timed: Readonly<Record<number, readonly [fingerprint: string, bytes: number]>>;');
lines.push('};');
lines.push('');
lines.push('export const GENERATED_RECITERS: readonly GeneratedReciter[] = [');
for (const r of RECITERS) {
  const a = byId.get(r.id);
  if (!a) throw new Error(`no audit result for ${r.id}`);
  if (!('timingSource' in a)) throw new Error('audit-results.json has not been refined: run refine-results.mjs');
  const timed = Object.entries(a.timed).map(([s, t]) => `${s}: ['${t.fingerprint}', ${a.bytes[s]}]`);
  lines.push('  {');
  lines.push(`    id: '${r.id}', nameEn: '${r.nameEn}', nameAr: '${r.nameAr}', mp3quranReciterId: ${r.reciterId}, moshafId: ${r.moshafId},`);
  const q = (v) => (v === null ? 'null' : `'${v}'`);
  lines.push(`    server: ${q(a.server)}, style: '${r.style}', riwayaLabel: ${q(r.riwayaLabel)},`);
  lines.push(`    timingSource: ${a.timingSource ? `'${a.timingSource}'` : 'null'}, timingRead: ${a.timingRead ?? 'null'},`);
  lines.push(`    surahs: [${a.surahs.join(', ')}],`);
  if (timed.length === 0) lines.push('    timed: {},');
  else {
    lines.push('    timed: {');
    for (let i = 0; i < timed.length; i += 4) lines.push(`      ${timed.slice(i, i + 4).join(', ')},`);
    lines.push('    },');
  }
  lines.push('  },');
}
lines.push('];');
lines.push('');
const generated = path.join(here, '..', '..', 'mobile', 'src', 'audio', 'generated');
fs.mkdirSync(generated, { recursive: true });
const target = path.join(generated, 'reciterCatalog.ts');
fs.writeFileSync(target, lines.join('\n'));
console.log('wrote', target, fs.statSync(target).size, 'bytes');

// Measured timing: per surah, the ayah boundaries in ms, delta-encoded (start of ayah 1, then each ayah's length).
// Every ayah ends where the next starts (the boundary sits in the measured pause), so N+1 numbers give N ayahs.
const m = [];
m.push('// GENERATED by tools/quran-audio/generate-catalog.mjs from tools/quran-audio/measured-timing.json. Do not edit.');
m.push("import type { TimingEntry } from '../timingFingerprint';");
m.push('');
m.push('/**');
m.push(' * Ayah timing measured by the audit (tools/quran-audio/refine-results.mjs) for reciters whose MP3Quran recording has no');
m.push(' * usable MP3Quran timing: per surah, in that same MP3Quran file, the start of ayah 1 and then each ayah\'s length (ms).');
m.push(" * Used only through audio/timing.ts, which checks it against the catalogue's fingerprint like any other timing.");
m.push(' */');
m.push('const MEASURED: Readonly<Record<string, Readonly<Record<number, readonly number[]>>>> = {');
for (const r of RECITERS) {
  const mr = measured.reciters[r.id];
  if (!mr) continue;
  if (byId.get(r.id).timingSource !== 'measured') throw new Error(`${r.id}: measured timing without timingSource 'measured'`);
  m.push(`  '${r.id}': {`);
  for (const [s, ayahs] of Object.entries(mr.surahs)) {
    ayahs.forEach(([, end], k) => {
      if (k + 1 < ayahs.length && end !== ayahs[k + 1][0]) throw new Error(`${r.id} ${s}:${k + 1} does not end where the next starts`);
    });
    const points = [...ayahs.map(([start]) => start), ayahs.at(-1)[1]];
    m.push(`    ${s}: [${points.map((p, k) => (k === 0 ? p : p - points[k - 1])).join(', ')}],`);
  }
  m.push('  },');
}
m.push('};');
m.push('');
m.push('/** The measured timing of one surah as timing entries (ayahs 1..N), or null when there is none. */');
m.push('export function measuredTimingEntries(reciterId: string, surah: number): TimingEntry[] | null {');
m.push('  const deltas = MEASURED[reciterId]?.[surah];');
m.push('  if (!deltas || deltas.length < 2) return null;');
m.push('  const entries: TimingEntry[] = [];');
m.push('  let at = deltas[0];');
m.push('  for (let k = 1; k < deltas.length; k++) {');
m.push('    entries.push({ ayah: k, startMs: at, endMs: at + deltas[k] });');
m.push('    at += deltas[k];');
m.push('  }');
m.push('  return entries;');
m.push('}');
m.push('');
const measuredTarget = path.join(generated, 'measuredTiming.ts');
fs.writeFileSync(measuredTarget, m.join('\n'));
console.log('wrote', measuredTarget, fs.statSync(measuredTarget).size, 'bytes');

// The source registry's data (mobile/src/audio/sourceRegistry.ts builds every source from it and the catalogue):
// the providers and their permissions, each recording's file format (audit-data/recording-formats-*.json), and the
// whole-surah sources approved in surah-mode-approvals.json.
const formatsFile = fs.readdirSync(path.join(here, 'audit-data')).filter((f) => /^recording-formats-.*\.json$/.test(f)).sort().at(-1);
if (!formatsFile) throw new Error('no audit-data/recording-formats-*.json: run audit/extract-formats.mjs');
const formats = JSON.parse(fs.readFileSync(path.join(here, 'audit-data', formatsFile), 'utf8'));
const approvals = JSON.parse(fs.readFileSync(path.join(here, 'surah-mode-approvals.json'), 'utf8')).approved;
const providerById = new Map(PROVIDERS.map((p) => [p.id, p]));
const js = (value) => JSON.stringify(value).replace(/'/g, "\\'").replace(/^"|"$/g, "'").replace(/\\"/g, '"');
const str = (value) => (value === null ? 'null' : js(value));

const g = [];
g.push(`// GENERATED by tools/quran-audio/generate-catalog.mjs from providers.mjs, audit-data/${formatsFile} and surah-mode-approvals.json. Do not edit.`);
g.push('');
g.push('export type GeneratedPermission = { permitted: boolean; evidence: string };');
g.push('export type GeneratedProvider = {');
g.push('  id: string;');
g.push('  name: string;');
g.push('  website: string;');
g.push('  streaming: GeneratedPermission;');
g.push('  offline: GeneratedPermission;');
g.push('  attribution: { required: boolean; text: string; shownIn: string } | null;');
g.push("  /** The provider answers a missing file with another recording's file (MP3Quran: Minshawi r1). */");
g.push('  redirectsUnlisted: boolean;');
g.push('};');
g.push('');
g.push('/** The audio providers and what each permits, with the evidence (tools/quran-audio/providers.mjs). */');
g.push('export const GENERATED_PROVIDERS: readonly GeneratedProvider[] = [');
for (const p of PROVIDERS) {
  g.push('  {');
  g.push(`    id: '${p.id}', name: ${str(p.name)}, website: ${str(p.website)}, redirectsUnlisted: ${p.redirectsUnlisted},`);
  g.push(`    streaming: { permitted: ${p.streaming.permitted}, evidence: ${str(p.streaming.evidence)} },`);
  g.push(`    offline: { permitted: ${p.offline.permitted}, evidence: ${str(p.offline.evidence)} },`);
  g.push(`    attribution: ${p.attribution ? `{ required: ${p.attribution.required}, text: ${str(p.attribution.text)}, shownIn: ${str(p.attribution.shownIn)} }` : 'null'},`);
  g.push('  },');
}
g.push('];');
g.push('');
g.push("export type BitrateMode = 'cbr' | 'vbr';");
g.push("/** 'info-tag' / 'xing-tag': the encoder's own CBR / VBR header frame; 'first-frame': classified from the first frame only. */");
g.push("export type BitrateEvidence = 'info-tag' | 'xing-tag' | 'first-frame';");
g.push('export type GeneratedRecordingFormat = {');
g.push('  auditedOn: string;');
g.push('  kbps: number;');
g.push('  sampleRateHz: number;');
g.push('  bitrateMode: BitrateMode;');
g.push('  bitrateEvidence: BitrateEvidence;');
g.push('  /** Byte-range requests answered (needed for seeking a stream). */');
g.push('  rangeRequests: boolean;');
g.push('  /** Surahs whose file differs from the above: [kbps, sample rate, mode, evidence]. */');
g.push('  exceptions: Readonly<Record<number, readonly [number, number, BitrateMode, BitrateEvidence]>>;');
g.push('};');
g.push('');
g.push(`/** Each MP3Quran recording's file format, by reciter id (first 64 KB of every listed file, ${formats.auditedOn}). */`);
g.push('export const GENERATED_FORMATS: Readonly<Record<string, GeneratedRecordingFormat>> = {');
for (const r of RECITERS) {
  const a = byId.get(r.id);
  const rec = formats.recordings[r.id];
  if (a.moshafId === null) continue;
  if (!rec || rec.moshafId !== a.moshafId) throw new Error(`${r.id}: no format evidence for moshaf ${a.moshafId}`);
  const files = Object.entries(rec.files);
  const key = (f) => `${f.kbps}|${f.sampleRateHz}|${f.bitrateMode}|${f.bitrateEvidence}`;
  const counts = new Map();
  for (const [, f] of files) counts.set(key(f), (counts.get(key(f)) ?? 0) + 1);
  const common = [...counts.entries()].sort((x, y) => y[1] - x[1])[0][0];
  const [kbps, sr, mode, evidence] = common.split('|');
  for (const s of Object.keys(a.timed)) {
    // Ayah playback needs exact seeks: a VBR file seeks to within 0.5-1.8 s. Never generate one as timed.
    if (rec.files[s].bitrateMode !== 'cbr') throw new Error(`${r.id} ${s}: VBR file with verified timing; exclude it from ayah playback first`);
    if (rec.files[s].bytes !== a.bytes[s]) throw new Error(`${r.id} ${s}: format evidence is for another file size`);
  }
  const exceptions = files.filter(([, f]) => key(f) !== common).map(([s, f]) => `${s}: [${f.kbps}, ${f.sampleRateHz}, '${f.bitrateMode}', '${f.bitrateEvidence}']`);
  const ranges = files.every(([, f]) => f.rangeRequests);
  g.push(`  '${r.id}': { auditedOn: '${formats.auditedOn}', kbps: ${kbps}, sampleRateHz: ${sr}, bitrateMode: '${mode}', bitrateEvidence: '${evidence}', rangeRequests: ${ranges}, exceptions: { ${exceptions.join(', ')} } },`);
}
g.push('};');
g.push('');
g.push('export type GeneratedCheck = { method: string; evidence: string; checkedOn: string };');
g.push('export type GeneratedSurahOnlySource = {');
g.push('  reciterId: string;');
g.push('  surah: number;');
g.push('  provider: string;');
g.push('  url: string;');
g.push('  bytes: number;');
g.push('  kbps: number;');
g.push('  sampleRateHz: number;');
g.push('  bitrateMode: BitrateMode;');
g.push('  /** The verified length (the app refuses a loaded stream of another length). */');
g.push('  durationMs: number;');
g.push('  completeness: GeneratedCheck;');
g.push('  identity: GeneratedCheck;');
g.push("  riwayah: { value: 'hafs'; evidence: string };");
g.push('  listening: { by: string; on: string; notes: string };');
g.push('  approvedBy: string;');
g.push('  approvedOn: string;');
g.push('};');
g.push('');
g.push('/**');
g.push(' * Whole-surah sources approved for surah-only playback (tools/quran-audio/surah-mode-approvals.json): complete, the');
g.push(" * right reciter and riwayah, streaming permitted, checked by a person's listening. Only for surahs without verified");
g.push(' * ayah timing; never used for ayah playback.');
g.push(' */');
g.push('export const GENERATED_SURAH_ONLY: readonly GeneratedSurahOnlySource[] = [');
const seen = new Set();
for (const ap of approvals) {
  const where = `surah-mode-approvals.json ${ap.reciterId} ${ap.surah}`;
  const need = (cond, why) => { if (!cond) throw new Error(`${where}: ${why}`); };
  const a = byId.get(ap.reciterId);
  need(a, 'unknown reciter');
  need(Number.isInteger(ap.surah) && ap.surah >= 1 && ap.surah <= 114, 'surah must be 1-114');
  need(!seen.has(`${ap.reciterId}:${ap.surah}:${ap.provider}`), 'listed twice');
  seen.add(`${ap.reciterId}:${ap.surah}:${ap.provider}`);
  const provider = providerById.get(ap.provider);
  need(provider, `unknown provider ${ap.provider}`);
  need(provider.streaming.permitted, `${provider.name} does not permit streaming (providers.mjs): it cannot be activated`);
  need(a.timed[ap.surah] === undefined, 'this surah has verified ayah timing: ayah playback is used, never a whole-surah source');
  for (const field of ['completeness', 'identity']) {
    need(ap[field] && ap[field].method && ap[field].evidence && /^\d{4}-\d\d-\d\d$/.test(ap[field].checkedOn ?? ''), `${field}: method, evidence and checkedOn are required`);
  }
  need(ap.riwayah?.value === 'hafs' && ap.riwayah.evidence, "riwayah: { value: 'hafs', evidence } is required");
  need(ap.listening?.by && /^\d{4}-\d\d-\d\d$/.test(ap.listening.on ?? ''), 'listening: by and on are required (a person listened)');
  need(ap.approvedBy && /^\d{4}-\d\d-\d\d$/.test(ap.approvedOn ?? ''), 'approvedBy and approvedOn are required');
  need(Number.isInteger(ap.durationMs) && ap.durationMs > 0, 'durationMs (the verified length, measured on the file) is required');
  let format;
  if (ap.provider === 'mp3quran') {
    need(a.surahs.includes(ap.surah), "not in MP3Quran's catalogue for this recording (its CDN would redirect it to another reciter)");
    need(ap.url === `${a.server}${String(ap.surah).padStart(3, '0')}.mp3`, 'url must be the catalogue file of this recording');
    need(ap.bytes === a.bytes[ap.surah], `bytes ${ap.bytes} ≠ audited ${a.bytes[ap.surah]}`);
    format = formats.recordings[ap.reciterId].files[ap.surah];
    // The audit's own estimate of the same file's length must agree (a CBR estimate from its size, or the VBR frame count).
    if (format.durationMs) need(Math.abs(ap.durationMs - format.durationMs) <= Math.max(3000, format.durationMs * 0.03), `durationMs ${ap.durationMs} disagrees with the audited ${format.durationMs}`);
  } else {
    need(ap.format && Number.isFinite(ap.format.kbps) && Number.isFinite(ap.format.sampleRateHz) && ['cbr', 'vbr'].includes(ap.format.bitrateMode), 'format { kbps, sampleRateHz, bitrateMode } is required');
    need(Number.isInteger(ap.bytes) && ap.bytes > 0, 'bytes required');
    format = ap.format;
  }
  g.push(`  { reciterId: '${ap.reciterId}', surah: ${ap.surah}, provider: '${ap.provider}', url: ${str(ap.url)}, bytes: ${ap.bytes}, durationMs: ${ap.durationMs}, kbps: ${format.kbps}, sampleRateHz: ${format.sampleRateHz}, bitrateMode: '${format.bitrateMode}',`);
  g.push(`    completeness: { method: ${str(ap.completeness.method)}, evidence: ${str(ap.completeness.evidence)}, checkedOn: '${ap.completeness.checkedOn}' },`);
  g.push(`    identity: { method: ${str(ap.identity.method)}, evidence: ${str(ap.identity.evidence)}, checkedOn: '${ap.identity.checkedOn}' },`);
  g.push(`    riwayah: { value: 'hafs', evidence: ${str(ap.riwayah.evidence)} },`);
  g.push(`    listening: { by: ${str(ap.listening.by)}, on: '${ap.listening.on}', notes: ${str(ap.listening.notes ?? '')} }, approvedBy: ${str(ap.approvedBy)}, approvedOn: '${ap.approvedOn}' },`);
}
g.push('];');
g.push('');
const registryTarget = path.join(generated, 'sourceRegistry.ts');
fs.writeFileSync(registryTarget, g.join('\n'));
console.log('wrote', registryTarget, fs.statSync(registryTarget).size, 'bytes', `(${approvals.length} whole-surah sources)`);

// DEVELOPMENT-ONLY timing (development/development-timing.json, from development/supplement-measured.mjs): measured
// timing for surahs with no production timing, loaded by the app in development builds only (reciters.ts, __DEV__).
// Production files above are never affected by it.
const devFile = path.join(here, 'development', 'development-timing.json');
const dev = fs.existsSync(devFile) ? JSON.parse(fs.readFileSync(devFile, 'utf8')) : { generatedOn: null, reciters: {} };
const d = [];
d.push('// GENERATED by tools/quran-audio/generate-catalog.mjs from tools/quran-audio/development/development-timing.json. Do not edit.');
d.push('/**');
d.push(' * DEVELOPMENT-ONLY ayah timing: measured (audit/align_everyayah.py, the production measured rules, boundary sweep) for');
d.push(' * surahs that have no production timing. Loaded only in development builds (audio/reciters.ts, __DEV__): never in a');
d.push(" * release until the owner's listening review promotes it. Per reciter and surah: the fingerprint, the audio file's");
d.push(" * size, and the timing delta-encoded like generated/measuredTiming.ts (ayah 1's start, then each ayah's length).");
d.push(' */');
d.push(`export const DEVELOPMENT_TIMING_GENERATED_ON: string | null = ${dev.generatedOn ? `'${dev.generatedOn}'` : 'null'};`);
d.push('export const DEVELOPMENT_TIMING: Readonly<Record<string, Readonly<Record<number, { fingerprint: string; bytes: number; deltas: readonly number[] }>>>> = {');
for (const r of RECITERS) {
  const dr = dev.reciters[r.id];
  if (!dr || Object.keys(dr.surahs).length === 0) continue;
  const a = byId.get(r.id);
  d.push(`  '${r.id}': {`);
  for (const [s, ayahs] of Object.entries(dr.surahs)) {
    if (a.timed[s]) throw new Error(`${r.id} ${s}: development timing for a surah with production timing`);
    const ev = dr.evidence[s];
    if (ev.bytes !== a.bytes[s]) throw new Error(`${r.id} ${s}: development timing measured on another file size`);
    if (timingFingerprint(ayahs.map(([startMs, endMs], k) => ({ ayah: k + 1, startMs, endMs }))) !== ev.fingerprint) throw new Error(`${r.id} ${s}: fingerprint`);
    ayahs.forEach(([, end], k) => {
      if (k + 1 < ayahs.length && end !== ayahs[k + 1][0]) throw new Error(`${r.id} ${s}:${k + 1} does not end where the next starts`);
    });
    const points = [...ayahs.map(([start]) => start), ayahs.at(-1)[1]];
    d.push(`    ${s}: { fingerprint: '${ev.fingerprint}', bytes: ${ev.bytes}, deltas: [${points.map((p, k) => (k === 0 ? p : p - points[k - 1])).join(', ')}] },`);
  }
  d.push('  },');
}
d.push('};');
d.push('');
const devTarget = path.join(generated, 'developmentTiming.ts');
fs.writeFileSync(devTarget, d.join('\n'));
console.log('wrote', devTarget, fs.statSync(devTarget).size, 'bytes (development only)');
