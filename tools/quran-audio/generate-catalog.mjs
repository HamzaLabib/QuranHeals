// Writes mobile/src/audio/generated/reciterCatalog.ts from reciters.mjs and audit-results.json.
// usage: node generate-catalog.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { RECITERS } from './reciters.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const results = JSON.parse(fs.readFileSync(path.join(here, 'audit-results.json'), 'utf8'));
const byId = new Map(results.reciters.map((r) => [r.id, r]));

const lines = [];
lines.push('// GENERATED by tools/quran-audio/generate-catalog.mjs from tools/quran-audio/audit-results.json. Do not edit.');
lines.push('/**');
lines.push(` * The 16 Quran Heals reciters and the MP3Quran recording used for each (audited ${results.auditedOn}).`);
lines.push(' * `surahs`: the surahs the recording has. `timed`: the surahs whose MP3Quran ayah timing passed every check');
lines.push(' * (complete Kufan ayah set, ordered, inside the audio, and a pause at the stated boundaries in the audio itself), with');
lines.push(' * the fingerprint of the exact timing that was checked (audio/timingFingerprint.ts) and the audio file\'s size in bytes.');
lines.push(' * A surah missing from `timed` has no ayah playback for that reciter. See tools/quran-audio/README.md.');
lines.push(' */');
lines.push('export type GeneratedReciter = {');
lines.push('  id: string;');
lines.push('  nameEn: string;');
lines.push('  nameAr: string;');
lines.push('  mp3quranReciterId: number;');
lines.push('  moshafId: number;');
lines.push('  /** The recording\'s folder; a surah is `${server}${surah padded to 3}.mp3`. */');
lines.push('  server: string;');
lines.push("  style: 'murattal' | 'mujawwad';");
lines.push("  /** 'hafs': MP3Quran labels the recording حفص عن عاصم; 'unlabelled': it names no riwaya (Kufan ayah count verified). */");
lines.push("  riwayaLabel: 'hafs' | 'unlabelled';");
lines.push('  surahs: readonly number[];');
lines.push('  /** MP3Quran timing read id, or null when no timing is used. */');
lines.push('  timingRead: number | null;');
lines.push('  timed: Readonly<Record<number, readonly [fingerprint: string, bytes: number]>>;');
lines.push('};');
lines.push('');
lines.push('export const GENERATED_RECITERS: readonly GeneratedReciter[] = [');
for (const r of RECITERS) {
  const a = byId.get(r.id);
  if (!a) throw new Error(`no audit result for ${r.id}`);
  const timed = Object.entries(a.timed).map(([s, t]) => `${s}: ['${t.fingerprint}', ${a.bytes[s]}]`);
  lines.push('  {');
  lines.push(`    id: '${r.id}', nameEn: '${r.nameEn}', nameAr: '${r.nameAr}', mp3quranReciterId: ${r.reciterId}, moshafId: ${r.moshafId},`);
  lines.push(`    server: '${a.server}', style: '${r.style}', riwayaLabel: '${r.riwayaLabel}', timingRead: ${a.timingRead ?? 'null'},`);
  lines.push(`    surahs: [${a.surahs.join(', ')}],`);
  if (timed.length === 0) lines.push('    timed: {},');
  else {
    lines.push('    timed: {');
    for (let i = 0; i < timed.length; i += 4) lines.push(`      ${timed.slice(i, i + 4).join(', ')},`);
    lines.push('    },');
  }
  lines.push('  },');
}
lines.push('];');
lines.push('');
const target = path.join(here, '..', '..', 'mobile', 'src', 'audio', 'generated', 'reciterCatalog.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, lines.join('\n'));
console.log('wrote', target, fs.statSync(target).size, 'bytes');
