"""Ink of the words where an ayah selection can end, for the highlight (2026-10-12).

  python tools/mushaf-audit/generate_selection_ink.py <fonts dir> <records-*.json.gz>

Writes mobile/src/mushaf/generated/qpcV1SelectionInk.ts. A selection highlight covers an ayah's words on each line from
its first to its last word there; its ends are always one of: the first or last word of a line, or the first word after
an ayah-end medallion (the medallion itself is drawn by the app, its box is known there). QPC V1 glyphs draw ink outside
their advance (the box the layout gives the word): the dots and tooth of an initial letter, a kasra, a waqf sign. For
each such word this records how far its real ink (contours of every letter and mark, all glyphs of the word) reaches
past the advance on the left and on the right, in hundredths of an em, rounded up; words within 1/100 em are omitted.
Keys: page → "surah:ayah:position" (position in the ayah, as in the app's layout). A word of several glyphs is measured
as drawn: right to left (the codes are Arabic presentation forms, bidi class AL), its first glyph rightmost.
"""
import gzip, json, math, sys
from collections import defaultdict
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen

FONTS, RECORDS = sys.argv[1], sys.argv[2]
ROOT = Path(__file__).resolve().parents[2]
UPM = 2048
COUNTS = json.loads((ROOT / 'tools/quran-verification/surah-counts.json').read_text(encoding='utf-8'))['counts']
VERSE_KEYS = [f'{s + 1}:{a + 1}' for s, n in enumerate(COUNTS) for a in range(n)]
recs = [r for r in json.loads(gzip.open(RECORDS).read()) if r.get('record_type') == 'mushaf_word' and r.get('mushaf_id') == 2]
pages = defaultdict(list)
for r in recs: pages[r['page_number']].append(r)

entries = []
count = 0
for page in range(1, 605):
    f = TTFont(f'{FONTS}/p{page}.ttf'); cmap = f.getBestCmap(); gs = f.getGlyphSet(); hm = f['hmtx']
    bounds = {}
    def overflow(r):
        adv, lo, hi = 0, math.inf, -math.inf
        for ch in reversed(r['text']):  # drawn right to left (Arabic presentation forms): the first glyph rightmost
            n = cmap[ord(ch)]
            if n not in bounds:
                pen = BoundsPen(gs); gs[n].draw(pen); bounds[n] = pen.bounds
            b = bounds[n]
            if b: lo, hi = min(lo, adv + b[0]), max(hi, adv + b[2])
            adv += hm[n][0]
        return max(0, -lo), max(0, hi - adv)
    lines = defaultdict(list)
    for r in sorted(pages[page], key=lambda r: r['position_in_page']): lines[r['line_number']].append(r)
    edge = []
    for words in lines.values():
        edge += [words[0], words[-1]]
        edge += [words[i + 1] for i in range(len(words) - 1) if words[i]['char_type_name'] == 'end']
    out = {}
    for r in edge:
        if r['char_type_name'] == 'end': continue
        left, right = overflow(r)
        left, right = math.ceil(left / UPM * 100), math.ceil(right / UPM * 100)
        if left > 1 or right > 1:
            out[f"{VERSE_KEYS[r['verse_id'] - 1]}:{r['position_in_verse']}"] = (left, right)
    count += len(out)
    if out: entries.append(f'  {page}: {{ ' + ', '.join(f"'{k}': [{l}, {rt}]" for k, (l, rt) in out.items()) + ' },')

header = [
    '// GENERATED by tools/mushaf-audit/generate_selection_ink.py — do not edit.',
    "// Ink past the advance of the words where an ayah selection can end (a line's first and last word, the first word",
    '// after an ayah-end medallion): [left, right] in hundredths of an em, rounded up (real outlines of the QPC V1 page',
    '// fonts, Quran Foundation CDN, read 2026-10-12). Words within 1/100 em are omitted.',
    'export const QPC_V1_SELECTION_INK: Readonly<Record<number, Readonly<Record<string, readonly [left: number, right: number]>>>> = {',
]
(ROOT / 'mobile/src/mushaf/generated/qpcV1SelectionInk.ts').write_text('\n'.join(header + entries + ['};', '']), encoding='utf-8', newline='\n')
print('pages', len(entries), 'words', count)
