#!/usr/bin/env node
// Imports one Mushaf page from quran-ws/quran-svg (Hafs / KFQC edition) at a
// pinned release, verifies it, and writes a TypeScript module the mobile app
// bundles. Phase 1 (the /mushaf prototype) needs page 61 only.
//
//   node tools/mushaf/import-quran-svg-page.mjs 61
//
// Integrity: the SVG and mapping bytes must match the SHA-256 pinned below
// (recorded from the v1.1.1 tag), and every clickable ayah polygon in the
// SVG must agree with the JSON mapping. Nothing is transformed: the module
// carries the original bytes, and tests re-hash them.
//
// Licensing (see the repository's LICENSE and NOTICE.md at the tag): the page
// artwork belongs to the King Fahd Glorious Qur'an Printing Complex, whose
// published terms allow use in apps and software; the polygon layer and
// metadata are Quran.ws's, CC BY 4.0 with attribution waived inside products.

import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const REPOSITORY = 'quran-ws/quran-svg';
const TAG = 'v1.1.1';
const EDITION = 'hafs/kfqc';

/** Pinned per page: SHA-256 of `svg/NNN.svg` and `json/NNN.json` at TAG. */
const PINNED = {
  61: {
    svgSha256: '60bd941ffc69c001e9c5ac2820c88852c7f9fc280d22b478b70730b332d026dc',
    jsonSha256: '4e9bf6d103e890a7a29f1b67aecf90608602a2f8bbb66bc0e7cc7e4488ca5447',
  },
};

const sha256 = (text) => createHash('sha256').update(text, 'utf8').digest('hex');

async function fetchText(path) {
  const url = `https://raw.githubusercontent.com/${REPOSITORY}/${TAG}/mushafs/${EDITION}/${path}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} → HTTP ${response.status}`);
  return { url, text: await response.text() };
}

function validateMapping(mappingJson, svg, page) {
  const ayahs = JSON.parse(mappingJson);
  if (!Array.isArray(ayahs) || ayahs.length === 0) throw new Error(`Page ${page}: empty mapping`);
  for (const entry of ayahs) {
    if (!Number.isInteger(entry.surahNumber) || !Number.isInteger(entry.ayahNumber) || typeof entry.polygon !== 'string') {
      throw new Error(`Page ${page}: malformed mapping entry ${JSON.stringify(entry)}`);
    }
  }
  // The SVG's own hit layer must be the same ayahs, same order, same shapes.
  const svgPolygons = [...svg.matchAll(/<path class="ayahPolygon"[^>]*\bayah="(\d+)" surah="(\d+)" d="([^"]+)"/g)]
    .map((match) => ({ ayah: Number(match[1]), surah: Number(match[2]), d: match[3] }));
  if (svgPolygons.length !== ayahs.length) throw new Error(`Page ${page}: ${svgPolygons.length} SVG polygons vs ${ayahs.length} mapped ayahs`);
  ayahs.forEach((entry, index) => {
    const polygon = svgPolygons[index];
    if (polygon.surah !== entry.surahNumber || polygon.ayah !== entry.ayahNumber || polygon.d !== entry.polygon) {
      throw new Error(`Page ${page}: SVG polygon ${index} does not match the mapping`);
    }
  });
  return ayahs;
}

async function main() {
  const page = Number(process.argv[2]);
  const pinned = PINNED[page];
  if (!pinned) throw new Error(`Page ${process.argv[2]} is not pinned. Pinned: ${Object.keys(PINNED).join(', ')}`);
  const name = String(page).padStart(3, '0');

  const svg = await fetchText(`svg/${name}.svg`);
  const json = await fetchText(`json/${name}.json`);
  if (sha256(svg.text) !== pinned.svgSha256) throw new Error(`svg/${name}.svg does not match the pinned SHA-256`);
  if (sha256(json.text) !== pinned.jsonSha256) throw new Error(`json/${name}.json does not match the pinned SHA-256`);
  const ayahs = validateMapping(json.text, svg.text, page);

  const out = fileURLToPath(new URL(`../../mobile/src/mushaf/generated/hafsKfqcPage${name}.ts`, import.meta.url));
  mkdirSync(fileURLToPath(new URL('../../mobile/src/mushaf/generated/', import.meta.url)), { recursive: true });
  writeFileSync(out, [
    `// GENERATED by tools/mushaf/import-quran-svg-page.mjs — do not edit.`,
    `// ${REPOSITORY} ${TAG}, ${EDITION}, page ${page} (${ayahs.length} ayahs).`,
    `// Page artwork © King Fahd Glorious Qur'an Printing Complex (free for use in apps and software);`,
    `// ayah polygon layer and metadata © Quran.ws, CC BY 4.0 (attribution waived inside products).`,
    `import type { MushafPageSource } from '../mushafPage';`,
    ``,
    `export const HAFS_KFQC_PAGE_${name}: MushafPageSource = {`,
    `  page: ${page},`,
    `  edition: 'hafs-kfqc',`,
    `  source: {`,
    `    repository: '${REPOSITORY}',`,
    `    tag: '${TAG}',`,
    `    svgUrl: '${svg.url}',`,
    `    mappingUrl: '${json.url}',`,
    `    svgSha256: '${pinned.svgSha256}',`,
    `    mappingSha256: '${pinned.jsonSha256}',`,
    `  },`,
    `  // Original bytes, unmodified.`,
    `  svg: ${JSON.stringify(svg.text)},`,
    `  mappingJson: ${JSON.stringify(json.text)},`,
    `};`,
    ``,
  ].join('\n'));
  console.log(`Wrote ${out} — ${ayahs.length} ayahs (${ayahs[0].surahNumber}:${ayahs[0].ayahNumber}–${ayahs.at(-1).surahNumber}:${ayahs.at(-1).ayahNumber}).`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
