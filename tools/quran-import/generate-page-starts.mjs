// Builds mobile/src/mushaf/generated/pageStarts.ts: the first ayah of each of the 604 pages of the Madinah Mushaf,
// for the reader's navigation (the page selector's Surah and juz' preview, and the juz' / Hizb start pages). Derived
// from the same pinned Tanzil quran-data.xml as the Surah pages (generate-surah-pages.mjs, its <pages> table and
// parser), SHA-256-checked on every read; never re-fetched, never hand-edited, no other Quran source.
//
// Checked against Quran Foundation's QCF V1 (1405 AH) page records, the edition the reader draws: all 604 page starts
// agree (tools/mushaf/verify-offline-dataset.mjs, and mobile/tests/mushafNavigation.test.ts with a local snapshot).
//
// Usage:
//   node tools/quran-import/generate-page-starts.mjs [--verify|--generate]
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readVerifiedXml } from './generate-surah-names.mjs';
import { parsePages } from './generate-surah-pages.mjs';
import { repoRoot } from './tanzil-source.mjs';

export const outputPath = 'mobile/src/mushaf/generated/pageStarts.ts';

export function render(pages) {
  const rows = [];
  for (let i = 0; i < pages.length; i += 10) rows.push(`  ${pages.slice(i, i + 10).map((p) => `[${p.surah}, ${p.ayah}]`).join(', ')},`);
  return `// GENERATED by tools/quran-import/generate-page-starts.mjs from Tanzil's quran-data.xml (<pages>). Do not edit.
/**
 * The first ayah of each page of the 604-page Madinah Mushaf (index 0 = page 1): [surah, ayah]. A page belongs to the
 * Surah and juz' of the ayah it starts with. Agrees with Quran Foundation's QCF V1 (1405 AH) page records for all 604
 * pages, and with SURAH_START_PAGES and HIZB_QUARTER_STARTS (mobile/tests/mushafNavigation.test.ts).
 */
export const PAGE_FIRST_AYAH: readonly (readonly [number, number])[] = [
${rows.join('\n')}
];
`;
}

function main() {
  const mode = process.argv[2] ?? '--verify';
  const pages = parsePages(readVerifiedXml());
  const output = render(pages);
  const target = resolve(repoRoot, outputPath);
  if (mode === '--generate') {
    writeFileSync(target, output);
    console.log(`Wrote ${outputPath} (${pages.length} pages).`);
    return;
  }
  const current = readFileSync(target, 'utf8').split(String.fromCharCode(13)).join('');
  if (current !== output) throw new Error(`${outputPath} is out of date; run with --generate.`);
  console.log(`${outputPath} matches the pinned Tanzil source (${pages.length} pages).`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
