// Builds mobile/src/mushaf/generated/surahStartPages.ts: the 604-page Madinah
// Mushaf page on which each of the 114 Surahs begins (the page holding its
// first ayah, even when the Surah starts partway down that page). Derived
// from the same pinned Tanzil quran-data.xml as the Surah names
// (generate-surah-names.mjs) — its <pages> table gives each page's first
// ayah — never re-fetched and never hand-edited.
//
// Checked on 2026-10-11 against Quran Foundation's QCF V1 (1405 AH) page
// records (Content Sync `mushafs:2`, the edition the reader draws): all 604
// page starts and all 114 first pages agree. No Quran Foundation data is
// read or stored by this script.
//
// Usage:
//   node tools/quran-import/generate-surah-pages.mjs [--verify|--generate]
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSurahs, readVerifiedXml } from './generate-surah-names.mjs';
import { repoRoot } from './tanzil-source.mjs';

export const outputPath = 'mobile/src/mushaf/generated/surahStartPages.ts';
const PAGE_COUNT = 604;

/** Each page's first ayah, from <pages><page index sura aya/>…</pages>. */
export function parsePages(xml) {
  const pages = [...xml.matchAll(/<page\s+index="(\d+)"\s+sura="(\d+)"\s+aya="(\d+)"\s*\/>/g)].map((m) => ({ page: Number(m[1]), surah: Number(m[2]), ayah: Number(m[3]) }));
  if (pages.length !== PAGE_COUNT) throw new Error(`Expected ${PAGE_COUNT} pages, found ${pages.length}.`);
  pages.forEach((entry, index) => {
    if (entry.page !== index + 1) throw new Error(`Pages are not ordered 1..${PAGE_COUNT} at index ${index} (got ${entry.page}).`);
    const previous = pages[index - 1];
    if (previous && (entry.surah < previous.surah || (entry.surah === previous.surah && entry.ayah <= previous.ayah))) {
      throw new Error(`Page ${entry.page} does not start after page ${previous.page}.`);
    }
  });
  return pages;
}

/** The page holding ayah S:1 — the last page that starts at or before it. */
export function surahStartPages(pages, surahCount = 114) {
  const starts = [];
  for (let surah = 1; surah <= surahCount; surah++) {
    const page = pages.filter((p) => p.surah < surah || (p.surah === surah && p.ayah <= 1)).at(-1)?.page;
    if (!page) throw new Error(`No page found for surah ${surah}.`);
    starts.push(page);
  }
  for (let i = 1; i < starts.length; i++) {
    if (starts[i] < starts[i - 1]) throw new Error(`Surah ${i + 1} starts before surah ${i}.`);
  }
  if (starts[0] !== 1 || starts.at(-1) !== PAGE_COUNT) throw new Error('The first Surah must start on page 1 and the last on page 604.');
  return starts;
}

export function render(starts) {
  const rows = [];
  for (let i = 0; i < starts.length; i += 10) rows.push(`  ${starts.slice(i, i + 10).join(', ')},`);
  return `// GENERATED by tools/quran-import/generate-surah-pages.mjs from Tanzil's quran-data.xml (<pages>). Do not edit.
/**
 * The 604-page Madinah Mushaf page on which each Surah begins (index 0 =
 * Surah 1): the page holding its first ayah, even when the Surah starts
 * partway down it. Agrees with Quran Foundation's QCF V1 (1405 AH) pages for
 * all 114 Surahs (checked 2026-10-11).
 */
export const SURAH_START_PAGES: readonly number[] = [
${rows.join('\n')}
];
`;
}

function main() {
  const mode = process.argv[2] ?? '--verify';
  const xml = readVerifiedXml();
  const surahs = parseSurahs(xml);
  const starts = surahStartPages(parsePages(xml), surahs.length);
  const output = render(starts);
  const target = resolve(repoRoot, outputPath);
  if (mode === '--generate') {
    writeFileSync(target, output);
    console.log(`Wrote ${outputPath} (${starts.length} Surahs).`);
    return;
  }
  const current = readFileSync(target, 'utf8').split(String.fromCharCode(13)).join('');
  if (current !== output) throw new Error(`${outputPath} is out of date; run with --generate.`);
  console.log(`${outputPath} matches the pinned Tanzil source (${starts.length} Surahs).`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
