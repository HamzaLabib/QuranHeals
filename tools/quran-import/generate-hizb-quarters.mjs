// Builds mobile/src/mushaf/generated/hizbQuarters.ts: the 240 quarter-Hizb starts
// (60 Hizbs × 4: the Hizb, its quarter, half and three quarters) with the ayah each
// begins at and the 604-page Madinah Mushaf page holding that ayah. From the same
// pinned Tanzil quran-data.xml as the Surah pages (generate-surah-pages.mjs): its
// <hizbs><quarter …/> table and its <pages> table. Never hand-edited.
//
// Verified on 2026-10-12:
//  - Against Quran Foundation's verse metadata (api.quran.com v4,
//    verses/by_rub_el_hizb/N: the first verse of each rub' el-hizb): 239 of 240
//    quarters agree. Quarter 106 differs: Tanzil 15:50, Quran Foundation 15:49.
//  - Against the 1405 AH print itself (the QCF V1 page fonts, which draw the ۞
//    rub' el-hizb sign where the print has it): the ۞ is part of 15:49's first word
//    «۞ نَبِّئْ» (page 264), and 15:50 has none. Every other quarter start that does
//    not open a Surah carries the ۞ on its first word; those opening a Surah carry
//    the Surah heading instead, as in the print. So QUARTER_CORRECTIONS below holds
//    the one documented correction, and nothing else differs.
//  - Every page agrees with Quran Foundation's QCF V1 (1405 AH) layout (the page of
//    each start ayah's first word, Content Sync `mushafs:2`). No page holds more
//    than one start.
//
// Usage:
//   node tools/quran-import/generate-hizb-quarters.mjs [--verify|--generate]
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readVerifiedXml } from './generate-surah-names.mjs';
import { parsePages } from './generate-surah-pages.mjs';
import { repoRoot } from './tanzil-source.mjs';

export const outputPath = 'mobile/src/mushaf/generated/hizbQuarters.ts';
const QUARTER_COUNT = 240;

/** Where the 1405 AH print (and Quran Foundation) differ from Tanzil: verified, documented, the only ones. */
export const QUARTER_CORRECTIONS = Object.freeze({
  106: { surah: 15, ayah: 49, tanzil: '15:50', reason: 'The ۞ is printed on 15:49 «نَبِّئْ عِبَادِىٓ» (QCF V1 page 264); Quran Foundation agrees.' },
});

/** The 240 quarter starts, from <hizbs><quarter index sura aya/>…</hizbs>, with the documented corrections. */
export function parseQuarters(xml) {
  const quarters = [...xml.matchAll(/<quarter\s+index="(\d+)"\s+sura="(\d+)"\s+aya="(\d+)"\s*\/>/g)].map((m) => ({ quarter: Number(m[1]), surah: Number(m[2]), ayah: Number(m[3]) }));
  if (quarters.length !== QUARTER_COUNT) throw new Error(`Expected ${QUARTER_COUNT} quarters, found ${quarters.length}.`);
  for (const [index, fix] of Object.entries(QUARTER_CORRECTIONS)) {
    const entry = quarters[Number(index) - 1];
    if (`${entry.surah}:${entry.ayah}` !== fix.tanzil) throw new Error(`Quarter ${index}: Tanzil now has ${entry.surah}:${entry.ayah}, not ${fix.tanzil}; recheck the correction.`);
    entry.surah = fix.surah;
    entry.ayah = fix.ayah;
  }
  quarters.forEach((entry, index) => {
    if (entry.quarter !== index + 1) throw new Error(`Quarters are not ordered 1..${QUARTER_COUNT} at index ${index}.`);
    const previous = quarters[index - 1];
    if (previous && (entry.surah < previous.surah || (entry.surah === previous.surah && entry.ayah <= previous.ayah))) throw new Error(`Quarter ${entry.quarter} does not start after quarter ${previous.quarter}.`);
  });
  if (quarters[0].surah !== 1 || quarters[0].ayah !== 1) throw new Error('Quarter 1 must start at 1:1.');
  return quarters;
}

/** Each quarter with its page: the last page that starts at or before its ayah. */
export function quarterPages(quarters, pages) {
  return quarters.map((q) => {
    const page = pages.filter((p) => p.surah < q.surah || (p.surah === q.surah && p.ayah <= q.ayah)).at(-1)?.page;
    if (!page) throw new Error(`No page for quarter ${q.quarter}.`);
    return { ...q, hizb: Math.floor((q.quarter - 1) / 4) + 1, part: (q.quarter - 1) % 4, page };
  });
}

export function render(rows) {
  const lines = rows.map((r) => `  [${r.quarter}, '${r.surah}:${r.ayah}', ${r.page}],`);
  return `// GENERATED by tools/quran-import/generate-hizb-quarters.mjs from Tanzil's quran-data.xml (<hizbs>, <pages>),
// with its one documented correction (quarter 106: 15:49, as printed). Do not edit.
/**
 * The 240 quarter-Hizb starts of the 604-page Madinah Mushaf (QPC V1, 1405 AH):
 * [quarter 1–240, the ayah it begins at, the page holding that ayah]. Quarter q is
 * part (q − 1) % 4 (0 Hizb, 1 quarter, 2 half, 3 three quarters) of Hizb ⌈q / 4⌉.
 * Agrees with Quran Foundation's verse metadata and with the ۞ in the print.
 */
export const HIZB_QUARTER_STARTS: readonly (readonly [quarter: number, verseKey: string, page: number])[] = [
${lines.join('\n')}
];
`;
}

function main() {
  const mode = process.argv[2] ?? '--verify';
  const xml = readVerifiedXml();
  const rows = quarterPages(parseQuarters(xml), parsePages(xml));
  const output = render(rows);
  const target = resolve(repoRoot, outputPath);
  if (mode === '--generate') {
    writeFileSync(target, output);
    console.log(`Wrote ${outputPath} (${rows.length} quarters on ${new Set(rows.map((r) => r.page)).size} pages).`);
    return;
  }
  const current = readFileSync(target, 'utf8').split(String.fromCharCode(13)).join('');
  if (current !== output) throw new Error(`${outputPath} is out of date; run with --generate.`);
  console.log(`${outputPath} matches the pinned Tanzil source (${rows.length} quarters).`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
