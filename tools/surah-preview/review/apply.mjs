#!/usr/bin/env node
/**
 * Turns the reviewers' decisions (review/data/decisions.jsonl) into tools/surah-preview/reviewed-content.json, which
 * import.mjs then uses for the app's Topics. The only way any Topics become 'approved'; run it deliberately:
 *
 *   node tools/surah-preview/review/apply.mjs            # shows what it would write
 *   node tools/surah-preview/review/apply.mjs --write    # writes reviewed-content.json, then run import.mjs
 *
 * Per Surah, the latest decision counts (skips never change anything):
 *  - accept / edit → 'approved' with the decided text, the reviewer's name, the time and the decision's number;
 *  - reject → 'rejected': the app shows no topics for that Surah (never the rejected text);
 *  - a decision made on topics that have since changed in the source (its reviewedSha no longer matches) is not
 *    applied: that Surah needs a new review.
 * Nothing is approved unless a human recorded it in the dashboard.
 */
import { existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { loadRecords, TOOL_DIR } from './data.mjs';
import { openStore } from './store.mjs';

export const REVIEW_DIR = join(TOOL_DIR, 'review/data');
const OUT = join(TOOL_DIR, 'reviewed-content.json');

/**
 * The reviewed-content document from the log and the current records, and what was left out.
 * @param {{ store: { entries(): any[] }, records: any[] }} input
 * @returns {{ document: { note: string, sources: { id: string }[], surahs: Record<string, { themesAr: any }> }, stale: number[] }}
 */
export function buildReviewedContent({ store, records }) {
  // A skip leaves the Surah as its earlier decision left it.
  const latest = new Map();
  for (const entry of store.entries()) if (entry.action !== 'skip') latest.set(entry.surah, entry);
  const surahs = {};
  const stale = [];
  const usedSources = new Set();
  const defs = new Map();
  for (const record of records) for (const source of record.references.sources) if (source.id) defs.set(source.id, source);
  for (const [n, decision] of latest) {
    const record = records[n - 1];
    if (decision.reviewedSha !== record.currentSha) {
      stale.push(n);
      continue;
    }
    const sources = record.references.sources.map((source) => source.id).filter(Boolean);
    sources.forEach((id) => usedSources.add(id));
    surahs[String(n)] = {
      themesAr: {
        status: decision.action === 'reject' ? 'rejected' : 'approved',
        ...(decision.action === 'reject' ? {} : { items: decision.items }),
        sources,
        review: { reviewer: decision.reviewer, decidedAt: decision.at, decision: decision.seq, basis: decision.basis, action: decision.action },
      },
    };
  }
  const document = {
    note: 'Generated by tools/surah-preview/review/apply.mjs from human reviewers\' decisions (review/data/decisions.jsonl). Do not edit by hand.',
    sources: [...usedSources].map((id) => {
      const { title, publisher, url, retrieved } = defs.get(id) ?? {};
      return { id, title, publisher, url, retrieved };
    }),
    surahs,
  };
  return { document, stale };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const dataArg = process.argv.indexOf('--data');
  const store = openStore(dataArg > 0 ? process.argv[dataArg + 1] : REVIEW_DIR);
  const { records } = loadRecords();
  const { document, stale } = buildReviewedContent({ store, records });
  const counts = Object.values(document.surahs).reduce((acc, s) => ({ ...acc, [s.themesAr.status]: (acc[s.themesAr.status] ?? 0) + 1 }), {});
  console.log(`Decisions to apply: ${JSON.stringify(counts)}${stale.length ? `; stale (need a new review): ${stale.join(', ')}` : ''}.`);
  if (process.argv.includes('--write') && dataArg > 0) console.log('Not written: --write applies the real log only (review/data/).');
  else if (process.argv.includes('--write')) {
    writeFileSync(`${OUT}.partial`, `${JSON.stringify(document, null, 2)}\n`);
    renameSync(`${OUT}.partial`, OUT);
    console.log(`Wrote ${OUT}. Now run: node tools/surah-preview/import.mjs`);
  } else if (existsSync(OUT)) {
    const before = readFileSync(OUT, 'utf8');
    console.log(before === `${JSON.stringify(document, null, 2)}\n` ? 'reviewed-content.json is already up to date.' : 'reviewed-content.json would change (run with --write).');
  } else console.log('Dry run: nothing written (run with --write).');
}
