/**
 * The tafsir app file's rules, shared by build.mjs and the tests. They mirror mobile/src/tafsir/dataset.ts exactly: an
 * edition is accepted only when each Surah's entries are in order, never overlap, cover every ayah (Tanzil's counts)
 * and carry non-empty text. Node built-ins only.
 */
import { createHash } from 'node:crypto';

export const FORMAT = 'quran-heals-tafsir';
export const FORMAT_VERSION = 1;

export const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
export const hashOf = (algorithm, bytes) => createHash(algorithm).update(bytes).digest('hex');

/** Why `surahs` is not a complete, ordered edition, or null when it is. */
export function coverageProblem(surahs, counts) {
  if (!Array.isArray(surahs) || surahs.length !== 114) return 'surah count';
  for (let s = 0; s < 114; s += 1) {
    const list = surahs[s];
    if (!Array.isArray(list) || list.length === 0) return `surah ${s + 1}: no entries`;
    let next = 1;
    for (const entry of list) {
      if (!Array.isArray(entry) || entry.length !== 3) return `surah ${s + 1}: entry shape`;
      const [from, to, text] = entry;
      if (!Number.isInteger(from) || !Number.isInteger(to) || from !== next || to < from || to > counts[s]) return `surah ${s + 1}: ayahs ${from}–${to} out of sequence`;
      if (typeof text !== 'string' || text.trim() === '') return `surah ${s + 1}:${from}: empty commentary`;
      next = to + 1;
    }
    if (next !== counts[s] + 1) return `surah ${s + 1}: ayahs ${next}–${counts[s]} not covered`;
  }
  return null;
}

/** The app file, byte-for-byte deterministic for the same input. */
export function appFile(edition, source, surahs) {
  const doc = {
    format: FORMAT,
    version: FORMAT_VERSION,
    edition,
    language: 'ar',
    source,
    surahs,
  };
  return Buffer.from(`${JSON.stringify(doc)}\n`, 'utf8');
}

export function stats(surahs) {
  let entries = 0;
  let ranges = 0;
  for (const list of surahs) for (const [from, to] of list) {
    entries += 1;
    if (to !== from) ranges += 1;
  }
  return { entries, ranges };
}

/**
 * Normalises text the way every adapter must, and no further: line endings to \n, trailing spaces on a line and blank
 * lines at the ends removed. Letters, marks, punctuation and wording are never changed.
 */
export function tidy(text) {
  return String(text).replace(/\r\n?/g, '\n').split('\n').map((line) => line.replace(/[ \t ]+$/u, '')).join('\n').replace(/^\n+|\n+$/g, '');
}

/** The generated mobile/src/tafsir/generated/tafsirRelease.ts. */
export function releaseModule(release) {
  const line = (id) => {
    const r = release[id];
    return r.status === 'ready'
      ? `  ${id}: { status: 'ready', sha256: '${r.sha256}', bytes: ${r.bytes}, entries: ${r.entries}, ranges: ${r.ranges} },`
      : `  ${id}: { status: 'blocked', reason: '${r.reason}' },`;
  };
  return `// GENERATED by tools/tafsir/build.mjs — do not edit by hand. Holds no tafsir text: only each edition's release status,
// the SHA-256 and size of its verified app file, and its source record. An edition is 'ready' only after its source
// checksums, conversion, validation and redistribution rights were all verified (tools/tafsir/README.md, RIGHTS.md).

export type TafsirReleasePin = {
  status: 'ready';
  /** SHA-256 (hex) of the app file (assets/tafsir/<id>.json, or the downloaded file). */
  sha256: string;
  bytes: number;
  /** Number of commentary entries (an entry covers one ayah or a range). */
  entries: number;
  /** Ranges covering more than one ayah. */
  ranges: number;
};

export type TafsirReleaseEntry = TafsirReleasePin | { status: 'blocked'; reason: string };

export const TAFSIR_RELEASE: Readonly<Record<'muyassar' | 'saadi' | 'jalalayn' | 'zilal', TafsirReleaseEntry>> = {
${['muyassar', 'saadi', 'jalalayn', 'zilal'].map(line).join('\n')}
};
`;
}

/** The generated mobile/src/tafsir/generated/bundledTafsir.ts: a static require only when الميسر is ready. */
export function bundledModule(ready) {
  const head = `// GENERATED by tools/tafsir/build.mjs — do not edit by hand.
//
// التفسير الميسر is bundled (assets/tafsir/muyassar.json, git-ignored like the other third-party datasets) only once its
// release pin is 'ready' (tafsirRelease.ts). Until then this build carries no tafsir text and the loader returns null:
// a static require of a missing file would stop every bundle.

/** The bundled التفسير الميسر file (parsed JSON), or null when this build carries none. Required lazily, on first use. */
export function bundledMuyassar(): unknown {
`;
  return ready
    ? `${head}  // Required only here, and only when first needed (opening the tafsir reader): the app's start never parses it.
  return require('../../../assets/tafsir/muyassar.json');
}
`
    : `${head}  return null;
}
`;
}
