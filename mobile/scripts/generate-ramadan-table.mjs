#!/usr/bin/env node
/**
 * Generates src/mushaf/generated/ummAlQuraRamadan.ts: the first and last
 * civil (Gregorian) day of Ramadan for each Hijri year in range, from the
 * Umm al-Qura calendar (ICU's `islamic-umalqura`, the Saudi official
 * calendar; Node ships full ICU). Classifying a completed Khatma as Ramadan
 * then needs no Intl calendar support on the device (Hermes on iOS and
 * Android differs there): a fixed, reviewable table, checked day by day
 * against ICU by tests/ramadan.test.ts.
 *
 *   node scripts/generate-ramadan-table.mjs
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const FIRST_YEAR = 1400; // 1979–1980
const LAST_YEAR = 1500; // 2077

const format = new Intl.DateTimeFormat('en-u-ca-islamic-umalqura', { year: 'numeric', month: 'numeric', day: 'numeric', timeZone: 'UTC' });
const hijri = (time) => {
  const parts = Object.fromEntries(format.formatToParts(time).map((part) => [part.type, part.value]));
  return { year: Number.parseInt(parts.year, 10), month: Number.parseInt(parts.month, 10) };
};
const iso = (time) => new Date(time).toISOString().slice(0, 10);

const DAY = 86_400_000;
const rows = [];
let open = null;
for (let time = Date.UTC(1979, 0, 1); time <= Date.UTC(2078, 11, 31); time += DAY) {
  const { year, month } = hijri(time);
  if (month === 9 && open === null) open = { year, start: iso(time) };
  if (month !== 9 && open !== null) {
    rows.push({ ...open, end: iso(time - DAY) });
    open = null;
  }
}
const table = rows.filter((row) => row.year >= FIRST_YEAR && row.year <= LAST_YEAR);
if (table.length !== LAST_YEAR - FIRST_YEAR + 1) throw new Error(`Expected ${LAST_YEAR - FIRST_YEAR + 1} Ramadans, found ${table.length}`);

const out = `// GENERATED by scripts/generate-ramadan-table.mjs from ICU's islamic-umalqura calendar (Node ${process.versions.node}, ICU ${process.versions.icu}). Do not edit.
/** [Hijri year, first day of Ramadan, last day of Ramadan] as civil dates (YYYY-MM-DD), Umm al-Qura, ${FIRST_YEAR}–${LAST_YEAR} AH. */
export const UMM_AL_QURA_RAMADAN: readonly (readonly [number, string, string])[] = [
${table.map((row) => `  [${row.year}, '${row.start}', '${row.end}'],`).join('\n')}
];
`;
writeFileSync(fileURLToPath(new URL('../src/mushaf/generated/ummAlQuraRamadan.ts', import.meta.url)), out);
console.log(`Wrote ${table.length} Ramadans (${table[0].start} … ${table.at(-1).end}).`);
